plt.show()

def sanitize_input(user_input):
    """Strict Security Loop to sanitize and validate input, avoiding injection bugs."""
    # Allow only numeric values, decimal points, and spaces
    sanitized = re.sub(r'[^0-9.\s,]', '', str(user_input))
    return sanitized.strip()

def predict_user_pizza_sale(quantity, unit_price, total_price, pizza_size):
    """Predicts the pizza category based on input features with integrated security validation."""
    # Step 1: Secure & Sanitize inputs
    clean_qty = sanitize_input(quantity)
    clean_unit = sanitize_input(unit_price)
    clean_tot = sanitize_input(total_price)

    # Standardize size input defensively
    clean_size = str(pizza_size).strip().upper()
    if clean_size not in le_size.classes_:
        # Default fallback to most common size if input is invalid or malicious
        clean_size = 'L'

    try:
        qty_val = float(clean_qty) if clean_qty else 1.0
        unit_val = float(clean_unit) if clean_unit else 15.0
        tot_val = float(clean_tot) if clean_tot else qty_val * unit_val
        size_encoded = le_size.transform([clean_size])[0]

        # Prepare feature vector
        input_features = np.array([[qty_val, unit_val, tot_val, size_encoded]])
        prediction_encoded = model.predict(input_features)[0]
        predicted_category = le_target.inverse_transform([prediction_encoded])[0]

        print("\n--- Secured Prediction Results ---")
        print(f"Inputs received safely [Qty: {qty_val}, Unit Price: ${unit_val}, Total Price: ${tot_val}, Size: {clean_size}]")
        print(f"Predicted Pizza Category: {predicted_category}")

    except Exception as e:
        print(f"Security Alert: Input processing halted or malformed query detected: {e}")

# Test the secured predict function with a simulated user input
